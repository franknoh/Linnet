"""Triton Inference Server model repositories from Linnet models.

`export` writes one model directory the server loads as it is: a
`config.pbtxt` with the entry's inputs and outputs (names, dtypes, static
dims), and either a self-contained ONNX model for the `onnxruntime_onnx`
platform or a `model.py` for the Python backend that runs the entry through
`linnet.torch`.

    python -m linnet.triton export models/gpt2 -o model_repository --bind B=1 --bind S=64
    python -m linnet.triton export src/lib.linnet --weights weights/ --bind H=64 ... -o repo
"""

from __future__ import annotations

import argparse
import shutil
import sys
from collections.abc import Iterable, Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Literal

from . import ir, nest
from .compiler import LinnetError

TRITON_DTYPES = {
    "bool": "TYPE_BOOL",
    "i8": "TYPE_INT8",
    "i16": "TYPE_INT16",
    "i32": "TYPE_INT32",
    "i64": "TYPE_INT64",
    "u8": "TYPE_UINT8",
    "u16": "TYPE_UINT16",
    "u32": "TYPE_UINT32",
    "u64": "TYPE_UINT64",
    "f16": "TYPE_FP16",
    "bf16": "TYPE_BF16",
    "f32": "TYPE_FP32",
    "f64": "TYPE_FP64",
}


@dataclass(frozen=True, slots=True)
class Tensor:
    name: str
    dtype: str
    dims: tuple[int, ...]


@dataclass(frozen=True, slots=True)
class Repository:
    """What `export` wrote."""

    directory: Path
    name: str
    backend: Literal["onnx", "python"]
    inputs: tuple[Tensor, ...]
    outputs: tuple[Tensor, ...]

    @property
    def config(self) -> Path:
        return self.directory / "config.pbtxt"


def interface(
    program: ir.Program, entry: ir.Function, bindings: ir.Bindings
) -> tuple[tuple[Tensor, ...], tuple[Tensor, ...]]:
    """The entry's inputs and results with every dimension evaluated."""
    inputs: list[Tensor] = []
    for param in entry.params:
        if not isinstance(param.type, ir.TensorType | ir.ScalarType):
            raise LinnetError(f"input `{param.name}` is not a tensor; Triton cannot take it")
        inputs.append(_tensor(param.name, param.type, bindings))
    outputs: list[Tensor] = []
    for index, result in enumerate(entry.results):
        if not isinstance(result, ir.TensorType | ir.ScalarType):
            raise LinnetError("a result is not a tensor; Triton cannot return it")
        outputs.append(_tensor(f"output{index}", result, bindings))
    return tuple(inputs), tuple(outputs)


def _tensor(name: str, type: ir.TensorType | ir.ScalarType, bindings: ir.Bindings) -> Tensor:
    if isinstance(type, ir.ScalarType):
        return Tensor(name, ir.evaluate_dtype(type.dtype, bindings), ())
    return Tensor(
        name, ir.evaluate_dtype(type.dtype, bindings), ir.evaluate_shape(type.shape, bindings)
    )


def merge(*parts: ir.Bindings) -> ir.Bindings:
    dims: dict[int, int] = {}
    packs: dict[int, tuple[int, ...]] = {}
    dtypes: dict[int, str] = {}
    for part in parts:
        dims.update(part.dims)
        packs.update(part.packs)
        dtypes.update(part.dtypes)
    return ir.Bindings(dims, packs, dtypes)


def config_text(
    name: str,
    backend: Literal["onnx", "python"],
    inputs: Iterable[Tensor],
    outputs: Iterable[Tensor],
    *,
    lossy_bf16: bool = False,
) -> str:
    """`config.pbtxt` for static shapes (`max_batch_size: 0`)."""

    def block(kind: str, tensor: Tensor) -> str:
        dtype = tensor.dtype
        if lossy_bf16 and dtype == "bf16":
            dtype = "f32"
        dims = ", ".join(str(d) for d in tensor.dims) if tensor.dims else "1"
        reshape = "" if tensor.dims else "\n    reshape: { shape: [ ] }"
        return (
            f'{kind} [\n  {{\n    name: "{tensor.name}"\n    data_type: {TRITON_DTYPES[dtype]}\n'
            f"    dims: [ {dims} ]{reshape}\n  }}\n]"
        )

    head = (
        f'name: "{name}"\nplatform: "onnxruntime_onnx"\n'
        if backend == "onnx"
        else f'name: "{name}"\nbackend: "python"\n'
    )
    parts = [head + "max_batch_size: 0"]
    parts += [block("input", t) for t in inputs]
    parts += [block("output", t) for t in outputs]
    return "\n".join(parts) + "\n"


