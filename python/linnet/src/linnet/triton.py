def export(
    model: str | Path,
    output: str | Path,
    *,
    name: str | None = None,
    entry: str | None = None,
    generics: Mapping[str, int | str] | None = None,
    weights: str | Path | None = None,
    bindings: str | Path | None = None,
    root: str | None = None,
    std_root: str | Path | None = None,
    backend: Literal["onnx", "python"] = "onnx",
    numerics: str = "equivalent",
    version: int = 1,
    options: Mapping[str, object] | None = None,
) -> Repository:
    """Writes `<output>/<name>/` for Triton.

    `model` is a Nest model directory or registry name (its card supplies
    the source, generics, and checkpoint), or a `.linnet` file with
    `generics`, `weights`, and `bindings` given here. `generics` also binds
    the entry's own generics (`B`, `S`); with a card they add to its values.
    """
    card: nest.Card | None = None
    path = Path(model)
    if (path / "nest.toml").exists() or not path.exists():
        card = nest.resolve(model)
    values: dict[str, int | str] = {}
    if card is not None:
        values.update(card.generics)
        values.update(card.check)
        source = card.source_path
        root = card.root if root is None else root
        entry = card.entry if entry is None else entry
        if weights is None:
            weights = nest.download_weights(card)
        if bindings is None:
            bindings = card.bindings_path
    else:
        source = path
    values.update(generics or {})

    program = ir.load_program(source, root=root, std_root=std_root)
    function = program.entry(entry)
    root_bindings = ir.bind_generics(
        program.root.generics,
        {k: v for k, v in values.items() if k in {g.name for g in program.root.generics}},
    )
    entry_bindings = ir.bind_generics(
        function.generics,
        {k: v for k, v in values.items() if k in {g.name for g in function.generics}},
    )
    inputs, outputs = interface(program, function, merge(root_bindings, entry_bindings))
    if function.states and backend == "onnx":
        raise LinnetError(
            f"entry `{function.short_name}` uses state; export it with backend='python', "
            "which keeps the state between requests"
        )

    model_name = name or (card.name if card is not None else source.stem)
    directory = Path(output) / model_name
    version_dir = directory / str(version)
    version_dir.mkdir(parents=True, exist_ok=True)

    if backend == "onnx":
        if weights is None:
            raise LinnetError("an ONNX export needs weights")
        from .onnx.export import export_model

        exported = export_model(
            source,
            generics=values,
            weights=weights,
            entry=function.short_name,
            root=program.root.name,
            std_root=std_root,
            numerics=numerics,
            bindings=bindings,
        )
        exported.save(version_dir / "model.onnx")
        outputs = tuple(Tensor(o.name, o.dtype, o.shape) for o in exported.outputs)
        directory.joinpath("config.pbtxt").write_text(
            config_text(model_name, "onnx", inputs, outputs), encoding="utf-8"
        )
    else:
        target = version_dir / "model"
        if target.exists():
            shutil.rmtree(target)
        if card is not None:
            shutil.copytree(card.directory, target)
            source_name = card.source
        else:
            target.mkdir(parents=True)
            source_dir = source.parent
            for file in source_dir.rglob("*"):
                if file.is_file() and (file.suffix == ".linnet" or file.name == "linnet.toml"):
                    destination = target / file.relative_to(source_dir)
                    destination.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy(file, destination)
            source_name = source.name
            if weights is not None:
                weights_dir = version_dir / "weights"
                if weights_dir.exists():
                    shutil.rmtree(weights_dir)
                weights_path = Path(weights)
                if weights_path.is_dir():
                    shutil.copytree(weights_path, weights_dir)
                else:
                    weights_dir.mkdir()
                    shutil.copy(weights_path, weights_dir / weights_path.name)
                if bindings is not None:
                    shutil.copy(Path(bindings), weights_dir / "bindings.json")
        option_text = ", ".join(
            f"{k}={v!r}" for k, v in {"numerics": numerics, **(options or {})}.items()
        )
        version_dir.joinpath("model.py").write_text(
            _MODEL_PY.format(
                entry=function.short_name,
                inputs=[(t.name, t.dtype) for t in inputs],
                outputs=[(t.name, t.dtype) for t in outputs],
                generics={
                    k: v for k, v in values.items() if k in {g.name for g in program.root.generics}
                },
                entry_generics={
                    k: v for k, v in values.items() if k in {g.name for g in function.generics}
                },
                source=source_name,
                options=option_text,
            ),
            encoding="utf-8",
        )
        directory.joinpath("config.pbtxt").write_text(
            config_text(model_name, "python", inputs, outputs, lossy_bf16=True), encoding="utf-8"
        )
    return Repository(directory, model_name, backend, inputs, outputs)


def main(argv: Iterable[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m linnet.triton", description="Triton model repositories."
    )
    commands = parser.add_subparsers(dest="command", required=True)
    exp = commands.add_parser("export", help="write a model directory")
    exp.add_argument("model", help="a Nest model directory or name, or a .linnet file")
    exp.add_argument("-o", "--output", required=True, help="the model repository directory")
    exp.add_argument("--name", help="the model name (the card's or the file's by default)")
    exp.add_argument("--entry")
    exp.add_argument("--root")
    exp.add_argument("--std")
    exp.add_argument("--bind", action="append", default=[], metavar="NAME=VALUE")
    exp.add_argument("--weights", help="a SafeTensors file or directory (when not from a card)")
    exp.add_argument("--bindings", help="parameter path to tensor name JSON")
    exp.add_argument("--backend", choices=["onnx", "python"], default="onnx")
    exp.add_argument("--numerics", default="equivalent")
    exp.add_argument("--version", type=int, default=1)
    args = parser.parse_args(list(argv) if argv is not None else None)
    generics: dict[str, int | str] = {}
    for bind in args.bind:
        key, _, value = bind.partition("=")
        generics[key] = int(value) if value.lstrip("-").isdigit() else value
    try:
        repository = export(
            args.model,
            args.output,
            name=args.name,
            entry=args.entry,
            generics=generics,
            weights=args.weights,
            bindings=args.bindings,
            root=args.root,
            std_root=args.std,
            backend=args.backend,
            numerics=args.numerics,
            version=args.version,
        )
    except LinnetError as error:
        print(str(error), file=sys.stderr)
        return 1
    print(f"wrote {repository.directory} ({repository.backend})")
    for tensor in repository.inputs:
        print(f"  input  {tensor.name}: {tensor.dtype}{list(tensor.dims)}")
    for tensor in repository.outputs:
        print(f"  output {tensor.name}: {tensor.dtype}{list(tensor.dims)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
